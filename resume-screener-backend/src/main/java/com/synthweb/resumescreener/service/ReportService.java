    private static String extractJobTitle(String jobDescription) {
        if (!StringUtils.hasText(jobDescription)) {
            return "Position Not Specified";
        }
        String firstLine = jobDescription.lines().findFirst().orElse("Position Not Specified").trim();
        // Remove markdown headings if present
        firstLine = firstLine.replaceAll("^#+\\s*", "").trim();
        return firstLine.length() > 80 ? firstLine.substring(0, 80) + "…" : firstLine;
    }

    private static String formatGapType(String gapType) {
        if (gapType == null) return "Missing";
        return switch (gapType.toLowerCase()) {
            case "missing_skill" -> "Missing Skill";
            case "missing_evidence" -> "Missing Evidence";
            case "insufficient_depth" -> "Insufficient Depth";
            case "missing_qualification" -> "Missing Qualification";
            default -> gapType;
        };
    }

    private static String getBadgeClass(String status) {
        if (status == null) return "badge-new";
        return switch (status.toUpperCase()) {
            case "SHORTLISTED" -> "badge-shortlisted";
            case "UNDER_REVIEW" -> "badge-review";
            case "NOT_SUITABLE" -> "badge-not-suitable";
            default -> "badge-new";
        };
    }

    private static String escapeXml(String s) {
        if (s == null) return "";
        return s.replace("&", "&amp;")
                .replace("<", "&lt;")
                .replace(">", "&gt;")
                .replace("\"", "&quot;")
                .replace("'", "&apos;");
    }
