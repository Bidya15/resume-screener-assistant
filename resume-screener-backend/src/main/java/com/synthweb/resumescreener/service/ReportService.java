    private static final DateTimeFormatter DATE_FORMATTER = DateTimeFormatter.ofPattern("MMM dd, yyyy HH:mm 'UTC'")
            .withZone(ZoneId.of("UTC"));

    private static final String DISCLAIMER =
            "This report is generated by an artificial intelligence system (Synthweb Resume Screener Assistant) "
            + "to assist human recruiters and hiring managers. It does not constitute a final hiring decision. "
            + "All assessments are advisory and must be reviewed by qualified recruitment personnel.";

    /**
     * Generates a PDF byte array for an analysis report.
     *
     * @param analysis the analysis data to render
     * @return byte array containing the binary PDF content
     * @throws IOException if PDF rendering fails
     */
    public byte[] generatePdfReport(AnalysisResponse analysis) throws IOException {
        String html = buildReportHtml(analysis);

        try (ByteArrayOutputStream outputStream = new ByteArrayOutputStream()) {
            PdfRendererBuilder builder = new PdfRendererBuilder();
            builder.useFastMode();
            builder.withHtmlContent(html, null);
            builder.toStream(outputStream);
            builder.run();
            return outputStream.toByteArray();
        }
    }

